import * as fs from 'fs/promises';
import * as path from 'path';
import { JsonStorage } from '../data/storage/json-storage';
import { BacktestEngine } from '../backtest/engine';
import { ModularStrategy, type ExitMode } from '../strategies/modular-strategy';
import {
  getIntervalMs,
  performCandleSanityCheck,
  type Candle,
  type CandleInterval,
} from '../data/models/candle';

interface GridCombo {
  timeframe: CandleInterval;
  W: number;
  L: number;
  buyMin: number;
  buyMax: number;
  sellMin: number;
  sellMax: number;
  emaFast: number;
  emaSlow: number;
  exitMode: ExitMode;
}

interface ComboMetrics {
  trades: number;
  winRate: number;
  netReturnPercent: number;
  maxDrawdownPercent: number;
  profitFactor: number;
  avgHoldCandles: number;
  timeInPositionPercent: number;
  buyAndHoldPercent: number;
}

interface ComboResult {
  combo: GridCombo;
  key: string;
  train: ComboMetrics;
  test: ComboMetrics;
  calmarRatio: number;
  neighborAvgReturn?: number;
  isStable?: boolean;
}

// Check if candles are synthetic
function isDatasetSynthetic(candles: readonly Candle[]): boolean {
  if (candles.length === 0) return true;
  // If all volume values are integers within typical random bounds [500, 2500], it's generated by generateSyntheticCandles
  const sample = candles.slice(0, Math.min(200, candles.length));
  const allIntegerVolumes = sample.every((c) => Number.isInteger(c.volume));
  const typicalSyntheticRange = sample.every((c) => c.volume >= 500 && c.volume <= 2500);
  return allIntegerVolumes && typicalSyntheticRange;
}

function runBacktestSlice(
  strategy: ModularStrategy,
  candles: readonly Candle[],
  interval: CandleInterval
): ComboMetrics {
  const engine = new BacktestEngine();
  const result = engine.run({
    strategy,
    candles,
    initialBalance: 10000,
    tradeFeePercent: 0.1,
    positionSizePercent: 100,
  });

  const m = result.metrics;
  const intervalMs = getIntervalMs(interval);

  let totalHoldDurationMs = 0;
  for (const t of result.trades) {
    if (t.entryTime && t.exitTime) {
      totalHoldDurationMs += t.exitTime - t.entryTime;
    }
  }

  const avgHoldCandles =
    result.trades.length > 0
      ? totalHoldDurationMs / (result.trades.length * intervalMs)
      : 0;

  const totalPeriodMs =
    candles.length > 1
      ? candles[candles.length - 1].timestamp - candles[0].timestamp
      : 1;

  const timeInPositionPercent =
    totalPeriodMs > 0 ? (totalHoldDurationMs / totalPeriodMs) * 100 : 0;

  const firstPrice = candles[0].close;
  const lastPrice = candles[candles.length - 1].close;
  const buyAndHoldPercent = ((lastPrice - firstPrice) / firstPrice) * 100;

  let grossProfit = 0;
  let grossLoss = 0;
  for (const t of result.trades) {
    if (t.pnl > 0) grossProfit += t.pnl;
    else if (t.pnl < 0) grossLoss += Math.abs(t.pnl);
  }
  const profitFactor = grossLoss > 0 ? grossProfit / grossLoss : grossProfit > 0 ? 99.9 : 1.0;

  return {
    trades: m.totalTrades,
    winRate: Math.round(m.winRate * 1000) / 10,
    netReturnPercent: Math.round(m.totalPnlPercent * 100) / 100,
    maxDrawdownPercent: Math.round(m.maxDrawdownPercent * 100) / 100,
    profitFactor: Math.round(profitFactor * 100) / 100,
    avgHoldCandles: Math.round(avgHoldCandles * 10) / 10,
    timeInPositionPercent: Math.round(timeInPositionPercent * 10) / 10,
    buyAndHoldPercent: Math.round(buyAndHoldPercent * 100) / 100,
  };
}

async function runOptimization() {
  const args = process.argv.slice(2);
  let targetSymbol = 'BTCUSDT';
  for (const a of args) {
    if (a.startsWith('--symbol=')) {
      targetSymbol = a.slice('--symbol='.length).trim().toUpperCase();
    }
  }

  console.log('========================================================================');
  console.log(`  Strategy 1 (Triple Confluence) Parameter Optimization`);
  console.log(`  Symbol: ${targetSymbol}`);
  console.log('========================================================================\n');

  const storage = new JsonStorage();
  const timeframes: CandleInterval[] = ['1h', '4h', '15m'];

  // Grid definition
  const windows = [3, 6, 10];
  const lookbacks = [5, 10, 20];
  const buyRanges = [
    { min: 25, max: 35, label: '[25,35]' },
    { min: 20, max: 40, label: '[20,40]' },
    { min: 25, max: 40, label: '[25,40]' },
  ];
  const sellRanges = [
    { min: 65, max: 75, label: '[65,75]' },
    { min: 60, max: 80, label: '[60,80]' },
    { min: 60, max: 75, label: '[60,75]' },
  ];
  const emaPairs = [
    { fast: 10, slow: 30, label: '10/30' },
    { fast: 9, slow: 21, label: '9/21' },
    { fast: 20, slow: 50, label: '20/50' },
  ];
  const exitModes: ExitMode[] = ['mirror', 'emaCross', 'macdCross'];

  const allResults: ComboResult[] = [];

  for (const tf of timeframes) {
    const candles = await storage.loadCandles(targetSymbol, tf);

    if (!candles || candles.length === 0) {
      console.log(`[Skipping ${tf}] No cached candle file found in data/${targetSymbol}_${tf}.json.`);
      continue;
    }

    if (candles.length < 5000) {
      console.log(
        `[Skipping ${tf}] Dataset has only ${candles.length} candles (minimum required: 5000). Refusing to run on insufficient sample.`
      );
      continue;
    }

    if (isDatasetSynthetic(candles)) {
      console.log(
        `[Skipping ${tf}] Dataset in data/${targetSymbol}_${tf}.json was flagged as synthetic simulated data. Refusing to run optimizer on synthetic data.`
      );
      continue;
    }

    const sanity = performCandleSanityCheck(candles, tf);
    console.log(`\n------------------------------------------------------------------------`);
    console.log(`  Processing ${targetSymbol} on ${tf}: ${candles.length.toLocaleString()} real candles`);
    console.log(`  Span: ${new Date(sanity.firstTimestamp!).toISOString()} to ${new Date(sanity.lastTimestamp!).toISOString()}`);
    console.log(`  Price range: $${sanity.minClose} - $${sanity.maxClose} | Gaps (>1.5x interval): ${sanity.gapCount}`);
    console.log(`------------------------------------------------------------------------`);

    // Chronological split: 70% Train, 30% Test (never shuffle)
    const splitIndex = Math.floor(candles.length * 0.7);
    const trainCandles = candles.slice(0, splitIndex);
    const testCandles = candles.slice(splitIndex);

    console.log(`  Train set: ${trainCandles.length.toLocaleString()} candles | Test set: ${testCandles.length.toLocaleString()} candles`);
    console.log(`  Grid size: ${windows.length * lookbacks.length * buyRanges.length * sellRanges.length * emaPairs.length * exitModes.length} combinations...`);

    const tfResults: ComboResult[] = [];
    const resultMap = new Map<string, ComboResult>();

    let count = 0;
    const startTime = Date.now();

    for (let wIdx = 0; wIdx < windows.length; wIdx++) {
      const W = windows[wIdx];
      for (let lIdx = 0; lIdx < lookbacks.length; lIdx++) {
        const L = lookbacks[lIdx];
        for (let bIdx = 0; bIdx < buyRanges.length; bIdx++) {
          const buyR = buyRanges[bIdx];
          for (let sIdx = 0; sIdx < sellRanges.length; sIdx++) {
            const sellR = sellRanges[sIdx];
            for (let eIdx = 0; eIdx < emaPairs.length; eIdx++) {
              const ema = emaPairs[eIdx];
              for (let mIdx = 0; mIdx < exitModes.length; mIdx++) {
                const exitMode = exitModes[mIdx];
                count++;

                const key = `${tf}_W${wIdx}_L${lIdx}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`;
                const combo: GridCombo = {
                  timeframe: tf,
                  W,
                  L,
                  buyMin: buyR.min,
                  buyMax: buyR.max,
                  sellMin: sellR.min,
                  sellMax: sellR.max,
                  emaFast: ema.fast,
                  emaSlow: ema.slow,
                  exitMode,
                };

                const strategyTrain = new ModularStrategy({
                  ma: { enabled: true, type: 'ema', fastPeriod: ema.fast, slowPeriod: ema.slow },
                  rsi: { enabled: true, period: 14, buyMin: buyR.min, buyMax: buyR.max, sellMin: sellR.min, sellMax: sellR.max },
                  macd: { enabled: true, fastPeriod: 12, slowPeriod: 26, signalPeriod: 9 },
                  confirmationWindow: W,
                  rsiLookback: L,
                  exitMode,
                });

                const strategyTest = new ModularStrategy({
                  ma: { enabled: true, type: 'ema', fastPeriod: ema.fast, slowPeriod: ema.slow },
                  rsi: { enabled: true, period: 14, buyMin: buyR.min, buyMax: buyR.max, sellMin: sellR.min, sellMax: sellR.max },
                  macd: { enabled: true, fastPeriod: 12, slowPeriod: 26, signalPeriod: 9 },
                  confirmationWindow: W,
                  rsiLookback: L,
                  exitMode,
                });

                const trainMetrics = runBacktestSlice(strategyTrain, trainCandles, tf);
                const testMetrics = runBacktestSlice(strategyTest, testCandles, tf);

                const calmar = testMetrics.netReturnPercent / Math.max(0.01, testMetrics.maxDrawdownPercent);

                const res: ComboResult = {
                  combo,
                  key,
                  train: trainMetrics,
                  test: testMetrics,
                  calmarRatio: Math.round(calmar * 100) / 100,
                };

                tfResults.push(res);
                resultMap.set(key, res);
              }
            }
          }
        }
      }
    }

    const elapsedSec = ((Date.now() - startTime) / 1000).toFixed(1);
    console.log(`  Completed ${count} backtests in ${elapsedSec}s.`);

    // Calculate parameter stability for each candidate by averaging 1-step neighbors
    for (let wIdx = 0; wIdx < windows.length; wIdx++) {
      for (let lIdx = 0; lIdx < lookbacks.length; lIdx++) {
        for (let bIdx = 0; bIdx < buyRanges.length; bIdx++) {
          for (let sIdx = 0; sIdx < sellRanges.length; sIdx++) {
            for (let eIdx = 0; eIdx < emaPairs.length; eIdx++) {
              for (let mIdx = 0; mIdx < exitModes.length; mIdx++) {
                const key = `${tf}_W${wIdx}_L${lIdx}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`;
                const curr = resultMap.get(key);
                if (!curr) continue;

                const neighborKeys: string[] = [];
                if (wIdx > 0) neighborKeys.push(`${tf}_W${wIdx - 1}_L${lIdx}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (wIdx < windows.length - 1) neighborKeys.push(`${tf}_W${wIdx + 1}_L${lIdx}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (lIdx > 0) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx - 1}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (lIdx < lookbacks.length - 1) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx + 1}_B${bIdx}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (bIdx > 0) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx}_B${bIdx - 1}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (bIdx < buyRanges.length - 1) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx}_B${bIdx + 1}_S${sIdx}_E${eIdx}_M${mIdx}`);
                if (sIdx > 0) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx}_B${bIdx}_S${sIdx - 1}_E${eIdx}_M${mIdx}`);
                if (sIdx < sellRanges.length - 1) neighborKeys.push(`${tf}_W${wIdx}_L${lIdx}_B${bIdx}_S${sIdx + 1}_E${eIdx}_M${mIdx}`);

                let neighborSum = 0;
                let validCount = 0;
                for (const nk of neighborKeys) {
                  const nRes = resultMap.get(nk);
                  if (nRes) {
                    neighborSum += nRes.test.netReturnPercent;
                    validCount++;
                  }
                }

                const neighborAvg = validCount > 0 ? neighborSum / validCount : curr.test.netReturnPercent;
                curr.neighborAvgReturn = Math.round(neighborAvg * 100) / 100;
                curr.isStable = neighborAvg > 0;
              }
            }
          }
        }
      }
    }

    allResults.push(...tfResults);
  }

  if (allResults.length === 0) {
    console.error('\n❌ No valid datasets found with >= 5000 real candles to optimize. Exiting.');
    return;
  }

  // Filtering:
  // - Ignore combos with < 30 trades on train or < 10 on test
  // - Require positive net return on BOTH train and test
  const qualified = allResults.filter(
    (r) =>
      r.train.trades >= 30 &&
      r.test.trades >= 10 &&
      r.train.netReturnPercent > 0 &&
      r.test.netReturnPercent > 0
  );

  console.log(`\n========================================================================`);
  console.log(`  Optimization Summary`);
  console.log(`  Total evaluated: ${allResults.length.toLocaleString()} combos`);
  console.log(`  Qualified (Train Trades >= 30, Test Trades >= 10, Train Ret > 0, Test Ret > 0): ${qualified.length}`);
  console.log(`========================================================================\n`);

  // Rank by Calmar-like ratio on test set
  qualified.sort((a, b) => b.calmarRatio - a.calmarRatio);

  const top15 = qualified.slice(0, 15);

  // Print Top 15 Table to Console
  console.log('Top 15 Parameter Combinations (Ranked by Calmar-like Ratio = Test Return / Test MaxDD):');
  console.table(
    top15.map((r, i) => ({
      Rank: i + 1,
      TF: r.combo.timeframe,
      EMA: `${r.combo.emaFast}/${r.combo.emaSlow}`,
      W: r.combo.W,
      L: r.combo.L,
      RSI_Buy: `[${r.combo.buyMin},${r.combo.buyMax}]`,
      RSI_Sell: `[${r.combo.sellMin},${r.combo.sellMax}]`,
      Exit: r.combo.exitMode,
      'Train Ret%': `${r.train.netReturnPercent}%`,
      'Test Ret%': `${r.test.netReturnPercent}%`,
      'Test DD%': `${r.test.maxDrawdownPercent}%`,
      'Test WR%': `${r.test.winRate}%`,
      Trades: `${r.train.trades}/${r.test.trades}`,
      Calmar: r.calmarRatio,
      'Neighbor Avg%': `${r.neighborAvgReturn}%`,
      Stability: r.isStable ? 'Robust' : 'Fragile',
    }))
  );

  console.log('\n⚠️ IMPORTANT NOTE:');
  console.log('Past backtested performance is historical and does not guarantee future results.');
  console.log('Never select a single best row without verifying parameter stability across adjacent neighbor settings.\n');

  // Generate output files
  const dateStr = new Date().toISOString().split('T')[0];

  // 1. CSV Output
  const csvHeader =
    'Timeframe,EMA,W,L,BuyMin,BuyMax,SellMin,SellMax,ExitMode,TrainTrades,TrainWinRate,TrainNetReturn,TrainMaxDD,TrainPF,TestTrades,TestWinRate,TestNetReturn,TestMaxDD,TestPF,CalmarRatio,NeighborAvgReturn,Stability\n';
  const csvRows = allResults.map((r) =>
    [
      r.combo.timeframe,
      `${r.combo.emaFast}/${r.combo.emaSlow}`,
      r.combo.W,
      r.combo.L,
      r.combo.buyMin,
      r.combo.buyMax,
      r.combo.sellMin,
      r.combo.sellMax,
      r.combo.exitMode,
      r.train.trades,
      r.train.winRate,
      r.train.netReturnPercent,
      r.train.maxDrawdownPercent,
      r.train.profitFactor,
      r.test.trades,
      r.test.winRate,
      r.test.netReturnPercent,
      r.test.maxDrawdownPercent,
      r.test.profitFactor,
      r.calmarRatio,
      r.neighborAvgReturn ?? '',
      r.isStable ? 'Robust' : 'Fragile',
    ].join(',')
  );

  const csvPath = path.resolve(process.cwd(), 'data', `optimization_${targetSymbol}_${dateStr}.csv`);
  await fs.writeFile(csvPath, csvHeader + csvRows.join('\n'), 'utf-8');
  console.log(`✔ Full CSV report saved to: ${csvPath}`);

  // 2. Markdown Report
  const mdLines: string[] = [
    `# Parameter Optimization Report: ${targetSymbol}`,
    ``,
    `- **Date:** ${dateStr}`,
    `- **Symbol:** ${targetSymbol}`,
    `- **Engine:** BacktestEngine (Fee: 0.1%, Position: 100%, Initial Balance: $10,000)`,
    `- **Validation:** Chronological split (70% Train, 30% Test, no shuffle)`,
    `- **Total Evaluated Combinations:** ${allResults.length.toLocaleString()}`,
    `- **Combinations Passing Filter (Train Trades >= 30, Test Trades >= 10, Return > 0):** ${qualified.length}`,
    ``,
    `> **Disclaimer:** Historical backtest results do not guarantee future performance. Parameter selection should prioritize robust parameter neighborhoods over isolated peaks.`,
    ``,
    `## Top 15 Parameter Combinations`,
    ``,
    `| Rank | Timeframe | EMA | W | L | RSI Buy | RSI Sell | Exit Mode | Train Return | Test Return | Test MaxDD | Test WinRate | Trades (Train/Test) | Calmar Ratio | Neighbor Avg Return | Stability |`,
    `|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|`,
  ];

  for (let i = 0; i < top15.length; i++) {
    const r = top15[i];
    mdLines.push(
      `| ${i + 1} | ${r.combo.timeframe} | ${r.combo.emaFast}/${r.combo.emaSlow} | ${r.combo.W} | ${r.combo.L} | [${r.combo.buyMin},${r.combo.buyMax}] | [${r.combo.sellMin},${r.combo.sellMax}] | ${r.combo.exitMode} | ${r.train.netReturnPercent}% | ${r.test.netReturnPercent}% | ${r.test.maxDrawdownPercent}% | ${r.test.winRate}% | ${r.train.trades}/${r.test.trades} | ${r.calmarRatio} | ${r.neighborAvgReturn}% | ${r.isStable ? '✅ Robust' : '⚠️ Fragile'} |`
    );
  }

  mdLines.push(``);
  mdLines.push(`## Parameter Stability Analysis`);
  mdLines.push(`- **Robust:** The parameters surrounding this combination (one grid step away in W, L, RSI bounds, EMA periods) also generate positive returns on test data.`);
  mdLines.push(`- **Fragile:** Surrounding parameters generate negative average returns, indicating the combo may be an overfit outlier.`);

  const mdPath = path.resolve(process.cwd(), 'docs', 'strategies', `OPTIMIZATION_${targetSymbol}_${dateStr}.md`);
  await fs.writeFile(mdPath, mdLines.join('\n'), 'utf-8');
  console.log(`✔ Markdown report saved to: ${mdPath}`);

  // 3. Append to STRATEGIES_LOG.md
  const logPath = path.resolve(process.cwd(), 'docs', 'strategies', 'STRATEGIES_LOG.md');
  const logEntry = [
    `\n### Strategy 1 (Triple Confluence) Optimization - ${targetSymbol} (${dateStr})`,
    `- **Type:** Trend Following + Momentum Reversal (EMA + MACD + RSI)`,
    `- **Data:** Real candles from data/ (${allResults.length} combos tested)`,
    `- **Validation:** Chronological split (70% Train, 30% Test)`,
    `- **Best Ranked Setting:** ${top15[0] ? `TF: ${top15[0].combo.timeframe}, EMA: ${top15[0].combo.emaFast}/${top15[0].combo.emaSlow}, W: ${top15[0].combo.W}, L: ${top15[0].combo.L}, Exit: ${top15[0].combo.exitMode}, Test Return: ${top15[0].test.netReturnPercent}%, Calmar: ${top15[0].calmarRatio}` : 'None qualified'}`,
    `- **Detailed Report:** [OPTIMIZATION_${targetSymbol}_${dateStr}.md](./OPTIMIZATION_${targetSymbol}_${dateStr}.md)`,
    `- **Status:** ✅ Completed Optimization\n`,
  ].join('\n');

  try {
    await fs.appendFile(logPath, logEntry, 'utf-8');
    console.log(`✔ Updated docs/strategies/STRATEGIES_LOG.md with optimization summary.`);
  } catch {
    // Ignore log append failure
  }
}

runOptimization().catch(console.error);
